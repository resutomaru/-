-- lot_is_component — канон (= развёрнуто в БД). Детектор сборок/комплектов по ЗАГОЛОВКУ (§4.6).
-- false = сборка/комплект/лот/риг/ферма → НЕ отдельный компонент (исключается из медианы).
create or replace function public.lot_is_component(title text)
 returns boolean language plpgsql immutable
as $$
declare t text; ram_kit boolean;
begin
  t := lower(coalesce(title,''));
  -- САМОАУДИТ D7: в '+'-альтернации не было GPU-слов → «Материнская плата + RX580» шла в медиану mobo
  --   ценой бандла. Добавлены rx/rtx/gtx/gt/radeon/geforce/видеокарт + форма «с RX 580».
  -- САМОАУДИТ D8: «комплект» — три смысла. (a) «полный комплект» = коробка/документы → вырезаем фразу;
  --   (b) чистый RAM-кит («2x8GB комплект», «2+2 Гб») = товар-позиция (тотал считает pk_ram, E7) —
  --   кит-маркеры вырезаем, НО только если нет второго класса компонента/'+' (иначе это бандл);
  --   (c) прочий «комплект» = сборка → false, как раньше.
  t := regexp_replace(t, 'полн\w*\s*комплект\w*', ' ', 'g');
  ram_kit := t ~ '(памят|\yозу\y|оперативн|\yddr|dimm|мгц|mhz|hyperx)'  -- R8: кит узнаём и по частоте/hyperx
         and t !~ '(процессор|материнск|материнк|\yмать\y|видеокарт|geforce|\yrtx|\ygtx|radeon|\yssd\y|nvme|блок ?пит|\yбп\y|ryzen|\yi[3-9]|\yпк\y|сборк|\+\s*[^0-9])';
  if ram_kit then
    t := regexp_replace(t, 'комплект\w*', ' ', 'g');
    t := regexp_replace(t, '\d+\s*\+\s*\d+', ' ', 'g');
  end if;
  -- ПАКЕТ №4 (зонд qty, 12.06): количества — цена за N штук не должна попадать в полочку одиночного
  --   товара. «2+ шт/штук/pcs», «пара <предмет>», «2x Xeon/проц/плат…» (после x — БУКВЫ: RAM-киты
  --   «2x8GB» не флагуются, D8 жив). «1 шт» — одиночный, не флагуем.
  if t ~ 'комплект|в сборе|\y(сборка|лот|риг|ферма)\y|с процессором|с проц |с памятью|с видеокарт|с (rx|rtx|gtx)\s?\d|\+\s*(\d+\s*(gb|г|g)|ddr|i[3-9]|ryzen|cpu|проц|видеокарт|rx ?\d|rtx ?\d|gtx ?\d|gt ?\d{3}|radeon|geforce|[abhxz]\d{2,3}m?)|([2-9]|\d\d+)\s*(шт|штук\w*|pcs)\y|\yпар[аы]\s+(планок|памяти|модул\w*|процессор\w*|видеокарт\w*|плат)|\y[2-9]\s*[xх]\s*(xeon|проц\w*|cpu|i[3579]|ryzen|плат\w*|карт\w*|видеокарт\w*|ssd)'
     then return false; end if;
  return true;
end $$;

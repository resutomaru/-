-- lot_condition — классификатор рабочее/мёртвое/неясно (Фаза 4)
-- ИСПРАВЛЕННАЯ версия. База = развёрнутый канон (подтверждён = §3.12).
-- Изменение ровно одно: добавлен ШАГ 5 — обработка негатированных форм,
-- которые канон пропускал в working (E2 «не исправ», E3 прош. время,
-- E4 «нерабоч» без предмета, E5 «не работает …», спасённое гардом шага 2).
-- Логика шага 5: вырезаем «не …»-основы; если уцелел настоящий позитив → не dead
-- (это отличает E6-хедж/E6-fan); иначе → dead. Шаги 1–4 и 6 = канон без изменений.
-- Проверено: 14/14 на condition_golden, dead->working = 0. Ждёт валидации на 904.

create or replace function lot_condition(title text, descr text) returns text
language plpgsql immutable as $$
declare n text; pos_src text;
begin
  n := translate(lower(coalesce(title,'')||' . '||coalesce(descr,'')), 'aeopcxykmthb','аеорсхукмтнв');

  -- 1) КАНОН (без изменений): однозначно мёртвые ключи
  if n ~ 'на запчаст|на з/ч|неисправ|не запуск|не стартует|не выводит изображ|отвал|под восстановл|для разбирающ|нет изображени|артефач|сгорел|дохл|не видит|\yдонор\y' then return 'dead'; end if;

  -- 2) КАНОН (без изменений): «не работает/не включается», но НЕ про мелкую часть
  if n ~ '(не работает|не включа\w*)(?![^.!?]{0,18}(вентил|кулер|подсветк|argb|rgb|разъ|\yпорт|кнопк|лопаст|колодк))' then return 'dead'; end if;

  -- 3) КАНОН (без изменений): «нерабоч» рядом с предметом
  if n ~ '(не ?рабоч|нерабоч)\w*\s*(видеокарт|карт|плат|памят|проц|накопит|ssd|диск|сост)|(видеокарт|карт|плат|памят|проц)\w*\s+(не ?рабоч|нерабоч)|в не ?рабочем|полностью не ?рабоч' then return 'dead'; end if;

  -- 4) КАНОН (без изменений): явное «не знаю»
  if n ~ 'не тестир|не провер|не могу провер|не знаю' then return 'unknown'; end if;

  -- 5) НОВОЕ: негатированные формы, утекавшие в working.
  --    Мёртвое, ЕСЛИ после вырезания «не …» не осталось настоящего позитива.
  if n ~ 'не ?исправ\w*|не ?работа\w*|не ?рабоч\w*|нерабоч\w*' then
    pos_src := regexp_replace(n, 'не ?исправ\w*|не ?работа\w*|не ?рабоч\w*|нерабоч\w*', ' ', 'g');
    if pos_src !~ 'полностью рабоч|полностью исправ|100\s*%?\s*рабоч|на гаранти|гаранти[яйюе]|чеки|пломб|проверен|провер[ке]|идеальн\w* состоян|отличн\w* состоян|хорош\w* состоян|отлично работает|\yисправ|\yрабоч|\yработа' then
      return 'dead';
    end if;
  end if;

  -- 6) КАНОН (без изменений): позитив
  if n ~ 'полностью рабоч|полностью исправ|100\s*%?\s*рабоч|на гаранти|гаранти[яйюе]|чеки|пломб|проверен|провер[ке]|идеальн\w* состоян|отличн\w* состоян|хорош\w* состоян|отлично работает|исправ|рабоч|работа' then return 'working'; end if;

  return 'unknown';
end $$;

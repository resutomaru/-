-- lot_condition — классификатор рабочее/мёртвое/неясно (Фаза 4)
-- База = канон (= §3.12). Изменения относительно канона:
--   ШАГ 5  — обработка негаций с override (E2–E5): «не исправ», «не работа*», «нерабоч».
--   ШАГ 1+ — жёсткие сигналы смерти, которые НЕ спасает позитив (БП «перестал включаться»
--            при наличии «на пломбе»/«отработал» — реальный пропуск из working-выгрузки).
--   ШАГ 4b — «надо шить / под прошивку» → unknown (не готов к работе).
--   ШАГ 5+ — «перестал работать/запускаться», «сломан/слом» в мягкую ветку (с override).
--   ШАГ 1++ — E18-дочёс working (11.06, зонд по живым 893): заявленный дефект («с дефектом», кроме
--             коробки/упаковки), вылеты под нагрузкой (негации «не/без вылетает» уцелевают через
--             lookbehind), «не определяется», «замена на исправную». Позитив НЕ спасает: «работает,
--             но вылетает» = dead (асимметрия RR-05: тихо лучше, чем ложно).
-- Проверка: condition_golden (14 базовых + 4 новых), dead->working = 0.
--   R1 (ре-аудит 11.06, пакет №2): гард ШАГ 2 знал латинские argb|rgb — де-гомоглиф b→в делал их
--     недостижимыми («не работает RGB» → ложный dead). Теперь a?rg[bв].
--   R2 (ре-аудит 11.06, пакет №2): нормализация пробелов (\s+ → ' ') сразу после translate —
--     двойной пробел/перенос больше не пробивает lookbehind «не/без вылетает» и не раздувает гард-окна.
--   U-серия (11.06, пакет №3 — зонд unknown, 592 строки): dead += «под/на/нужен ремонт» (вкл. «нужно
--     обслуживание и ремонт»; с не-гардами), инверсия «изображения нет», «короткое замыкание», «красный
--     смарт», «бесконечная перезагрузка», «не проходит стресс/тест», «проржавели», «оторван/оторвалась»
--     (не-гард: «пломба не оторвана»); ШАГ 5 += «перестал чита/определя» («перестал читатся»). Позитивы +=
--     отрицательные конструкции («проблем/нареканий/претензий/дефектов/сбоев НЕТ», «без ремонтов»),
--     «не греется/не шумит», «проходит/выдерживает стресс/тест», «тянет игры» (не-гард), «здоровье
--     90–100%», «обслужен», «работоспособн» (не-гард), «не подводила», «живой блок/карта», «тесты ок»,
--     «проверял». ПОЗИТИВ-СПИСКИ РАЗЛИЧАЮТСЯ НАМЕРЕННО: в override ШАГ 5 — только СИЛЬНЫЕ утверждения
--     настоящего времени; слабые/прошедшие («без проблем», «не греется», «не подводила», «проверял»)
--     живут ТОЛЬКО в ШАГ 6 — труп («перестала работать») они спасать не должны.
--   ПОЛИТИКА (решение Алексея 11.06): «новый/запечатанный/не использовался» НЕ маппим в working —
--     новьё в б/у-медиане смещает её вверх → ложные «ниже рынка». Остаются unknown (вне медианы);
--     бонус новью в балле — задача Ф6. Спорная середина ~45 шт — кандидаты LLM-добивки (план-гибрид).

create or replace function lot_condition(title text, descr text) returns text
language plpgsql immutable as $$
declare n text; pos_src text;
begin
  n := translate(lower(coalesce(title,'')||' . '||coalesce(descr,'')), 'aeopcxykmthb','аеорсхукмтнв');
  n := regexp_replace(n, '\s+', ' ', 'g');  -- R2: схлопнуть пробелы/переносы (лукбихайды фикс-ширины)

  -- 1) ЖЁСТКО мёртвое (позитив не спасает)
  if n ~ 'на запчаст|на з/ч|неисправ|не запуск|не стартует|не выводит изображ|отвал|под восстановл|для разбирающ|нет изображени|артефач|сгорел|дохл|не видит|\yдонор\y'
     or n ~ 'перестал\w*\s+включа|не подаёт призн|не подает призн'
     or n ~ 'не определя|с дефект(?![^.!?]{0,12}(коробк|упаковк|внешн))|(?<!не\s)(?<!без\s)(?<!не)вылета|замен\w* на исправн'
     or n ~ '(\yпод|(?<!не\s)нужен|(?<!не\s)нужн[оа]|(?<!не\s)требует\w*)\s+(обслуживани[ея]\s+и\s+)?ремонт|изображени[яеи]\s+нет|коротк\w*\s+замыкан|красн\w*\s+смарт|бесконечн\w*\s+перезагруз|уходит в перезагруз|не проходит\s+(стресс|тест)|проржаве|(?<!не\s)оторва(н|лась|лся|ло)'
     then return 'dead'; end if;

  -- 2) КАНОН: «не работает/не включается», но не про мелкую часть
  if n ~ '(не работает|не включа\w*)(?![^.!?]{0,18}(вентил|кулер|подсветк|a?rg[bв]|разъ|\yпорт|кнопк|лопаст|колодк))' then return 'dead'; end if;

  -- 3) КАНОН: «нерабоч» рядом с предметом
  if n ~ '(не ?рабоч|нерабоч)\w*\s*(видеокарт|карт|плат|памят|проц|накопит|ssd|диск|сост)|(видеокарт|карт|плат|памят|проц)\w*\s+(не ?рабоч|нерабоч)|в не ?рабочем|полностью не ?рабоч' then return 'dead'; end if;

  -- 4) КАНОН: явное «не знаю»
  if n ~ 'не тестир|не провер|не могу провер|не знаю' then return 'unknown'; end if;

  -- 4b) НОВОЕ: требует прошивки → не готов к работе → unknown
  if n ~ 'надо шить|нужно шить|требует прошивк|нужна прошивк|под прошивк|на прошивк|на перепрошивк' then return 'unknown'; end if;

  -- 5) МЯГКО мёртвое: dead, ЕСЛИ после вырезания «не …»/«перестал …»-форм не уцелел сильный позитив
  if n ~ 'не ?исправ\w*|не ?работа\w*|не ?рабоч\w*|нерабоч\w*|перестал\w*\s+(работа|запуска|стартова|функц|чита|определя)\w*|сломан|сломал|\yслом\y' then
    pos_src := regexp_replace(n, 'не ?исправ\w*|не ?работа\w*|не ?рабоч\w*|нерабоч\w*|перестал\w*\s+(работа|запуска|стартова|функц|чита|определя)\w*', ' ', 'g');
    if pos_src !~ 'полностью рабоч|полностью исправ|100\s*%?\s*рабоч|на гаранти|гаранти[яйюе]|чеки|пломб|проверен|провер[ке]|идеальн\w* состоян|отличн\w* состоян|хорош\w* состоян|отлично работает|(проходит|выдерживает)\s+(стресс|тест|нагруз)\w*|(здоровь\w*|health)\D{0,10}(9\d|100)\s*%|(?<!не)(?<!не\s)работоспособн|\yжив(ой|ая|ое)\s+(блок|карт|плат|проц|памят|диск)|тест\w*\s+ок\y|\yисправ|\yрабоч|\yработа' then
      return 'dead';
    end if;
  end if;

  -- 6) КАНОН: позитив
  if n ~ 'полностью рабоч|полностью исправ|100\s*%?\s*рабоч|на гаранти|гаранти[яйюе]|чеки|пломб|проверен|провер[ке]|идеальн\w* состоян|отличн\w* состоян|хорош\w* состоян|отлично работает|(проходит|выдерживает)\s+(стресс|тест|нагруз)\w*|(здоровь\w*|health)\D{0,10}(9\d|100)\s*%|(?<!не)(?<!не\s)работоспособн|\yжив(ой|ая|ое)\s+(блок|карт|плат|проц|памят|диск)|тест\w*\s+ок\y|без (нарекани|проблем|дефект|ремонт|сбоев|ошибок)\w*|(нарекани|претензи|вопрос|проблем|сбо[её]в|ошибок|дефект)\w*\s+(нет|никаких|не был\w*|не возник\w*|не наблюда\w*|отсутств\w*)|никаких проблем|не греется|не грелась|не шумит|прошл[аио]\s+(стресс|тест|нагруз)\w*|прош[её]л\s+(стресс|тест|нагруз)\w*|(?<!не\s)тянет\s+(игр|соврем|вс[её])|обслужен|не подводил|тесты на фото|проверял|исправ|рабоч|работа' then return 'working'; end if;

  return 'unknown';
end $$;

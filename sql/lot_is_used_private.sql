-- lot_is_used_private — годен ли лот для МЕДИАНЫ (Ф5/Ф6, глазной тест E19).
-- Медиана = цена Б/У ЧАСТНОГО рынка. Новьё и магазины/опт задирают её → ложная «выгода» (RR-04).
-- true  = частное б/у → банкуем в price_history (источник медианы);
-- false = новое / запечатанное / магазин / опт / кредит-рассрочка / длинная гарантия → в медиану НЕ пускаем
--         (лот остаётся в lots; в Ф6 новьё по низкой цене получит бонус в балле — это отдельная ветка).
-- Найдено глазным тестом E19 (16.06): бакет ddr4-16gb-3200 вздулся 6000→7750 из-за «новая»/«кредит».
-- Гард «как новый/почти новый» (lookbehind) — это Б/У в отл. состоянии, его НЕ исключаем.
-- ВАЖНО: паттерн в СКОБКАХ — иначе `||` склеивается ПОСЛЕ `!~*` (приоритет операторов) и ломает типы.
-- ДЕ-ГОМОГЛИФ (как в lot_condition): продавцы маскируют латиницей («кpeдит», «нoвый») — translate()
--   латиница→кириллица, иначе паттерн их не видит (E19-превью поймало «кpeдит» 10000₽).
create or replace function public.lot_is_used_private(title text, descr text)
 returns boolean language sql immutable as $$
  select translate(lower(coalesce(title,'')||' '||coalesce(descr,'')), 'aeopcxykmthb','аеорсхукмтнв') !~* (
    -- НОВЬЁ (кроме «как/почти новый»):
       '(?<!как )(?<!почти )\yнов(ый|ая|ое|ые)\y|запечатан|не вскрыт|заводск\w*\s*упаковк|\yв пл[её]нке\y'
    -- МАГАЗИН / ОПТ / РАССРОЧКА / ДЛИННАЯ ГАРАНТИЯ:
    || '|\yоптом\y|\yопт\y|оптов|\yкредит\y|рассрочк|официальн\w*\s*гаранти'
    || '|гаранти\w*\s*(1[0-2]|[6-9])\s*мес|гаранти\w*\s*(год|года|лет)'
  );
$$;
